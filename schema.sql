-- Neon PostgreSQL schema. Applied automatically on application startup.
CREATE TABLE IF NOT EXISTS student (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    middle_name VARCHAR(80),
    last_name VARCHAR(80) NOT NULL,
    full_name_key VARCHAR(240),
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    student_class VARCHAR(10) NOT NULL CHECK (student_class IN ('SS1', 'SS2', 'SS3')),
    department VARCHAR(20) NOT NULL CHECK (department IN ('Science', 'Art', 'Commercial')),
    subjects_json TEXT NOT NULL DEFAULT '[]',
    exam_number VARCHAR(40) NOT NULL UNIQUE,
    download_token VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Safe additive migration for registrations created before full-name duplicate detection.
ALTER TABLE student ADD COLUMN IF NOT EXISTS full_name_key VARCHAR(240);
UPDATE student
SET full_name_key = lower(regexp_replace(trim(concat_ws(' ', first_name, middle_name, last_name)), '\s+', ' ', 'g'))
WHERE full_name_key IS NULL;
ALTER TABLE student ALTER COLUMN full_name_key SET NOT NULL;

CREATE INDEX IF NOT EXISTS ix_student_full_name_key ON student(full_name_key);
CREATE INDEX IF NOT EXISTS ix_student_email ON student(email);
CREATE INDEX IF NOT EXISTS ix_student_department ON student(department);
CREATE INDEX IF NOT EXISTS ix_student_exam_number ON student(exam_number);
CREATE INDEX IF NOT EXISTS ix_student_created_at ON student(created_at);
CREATE INDEX IF NOT EXISTS ix_student_download_token ON student(download_token);
